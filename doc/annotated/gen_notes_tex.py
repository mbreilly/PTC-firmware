"""Write notes.tex for the LaTeX version from changes_data.py.

Defines \\pnote{Cn} (a coloured margin tag with a link to the change log) and
\\changelogtable (every change with its full note and page).
"""
import re

from changes_data import CATEGORIES, CHANGES

ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
       "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}"}


def tex(s):
    s = "".join(ESC.get(c, c) for c in s)
    s = s.replace("+/-", r"$\pm$").replace("> ", r"$>$ ").replace("--", "-{}-")
    s = re.sub(r"(\d)-(\d)", r"\1--\2", s)
    s = re.sub(r"'([^']*)'", r"`\1'", s)
    return s


out = ["% generated by gen_notes_tex.py from changes_data.py -- do not edit by hand"]
for cat, (label, rgb) in CATEGORIES.items():
    out.append(r"\definecolor{cat%s}{rgb}{%.2f,%.2f,%.2f}" % (cat, *rgb))
    out.append(r"\expandafter\def\csname catlabel@%s\endcsname{%s}" % (cat, label))
for ch in CHANGES:
    out.append(r"\expandafter\def\csname pn@%s\endcsname{\pnotebox{%s}{%s}{%s}}"
               % (ch["id"], ch["id"], ch["cat"], tex(ch["title"])))
out.append(r"\newcommand{\changelogtable}{%")
out.append(r"\begin{longtable}{@{}p{0.07\linewidth}p{0.13\linewidth}p{0.63\linewidth}r@{}}")
out.append(r"\textbf{ID} & \textbf{Type} & \textbf{Change} & \textbf{Page}\\ \hline\endhead")
for ch in CHANGES:
    out.append(r"\textbf{\textcolor{cat%s}{%s}} & \textcolor{cat%s}{%s} & "
               r"\leavevmode\hypertarget{log:%s}{}\textbf{%s.} %s & \pageref{pn:%s}\\[3pt]"
               % (ch["cat"], ch["id"], ch["cat"], CATEGORIES[ch["cat"]][0], ch["id"],
                  tex(ch["title"]), tex(ch["text"]), ch["id"]))
out.append(r"\end{longtable}}")
open("notes.tex", "w").write("\n".join(out) + "\n")
print("wrote notes.tex with", len(CHANGES), "notes")
